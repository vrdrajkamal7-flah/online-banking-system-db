CREATE TABLE ob_banks (
    bank_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_code VARCHAR2(10) NOT NULL UNIQUE,
    bank_name VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE ob_users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR2(255) NOT NULL UNIQUE,
    mobile VARCHAR2(20),
    password_text VARCHAR2(255) NOT NULL,
    kyc_status VARCHAR2(20) DEFAULT 'not-started' NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_ob_users_kyc CHECK (kyc_status IN ('not-started','pending','approved','rejected'))
);

CREATE TABLE ob_accounts (
    account_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR2(30) NOT NULL UNIQUE,
    user_email VARCHAR2(255),
    name VARCHAR2(150) NOT NULL,
    company_name VARCHAR2(200),
    mobile VARCHAR2(20),
    email VARCHAR2(255),
    pin_text VARCHAR2(20) NOT NULL,
    balance NUMBER(15,2) DEFAULT 0 NOT NULL,
    bank_code VARCHAR2(10) NOT NULL,
    account_type VARCHAR2(20) DEFAULT 'self' NOT NULL,
    blocked NUMBER(1) DEFAULT 0 NOT NULL,
    kyc_status VARCHAR2(20) DEFAULT 'approved' NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_ob_accounts_balance CHECK (balance >= 0),
    CONSTRAINT ck_ob_accounts_blocked CHECK (blocked IN (0,1)),
    CONSTRAINT ck_ob_accounts_type CHECK (account_type IN ('self','business')),
    CONSTRAINT fk_ob_accounts_bank FOREIGN KEY (bank_code) REFERENCES ob_banks(bank_code),
    CONSTRAINT fk_ob_accounts_user FOREIGN KEY (user_email) REFERENCES ob_users(email)
);

CREATE TABLE ob_transactions (
    transaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_account VARCHAR2(30) NOT NULL,
    receiver_account VARCHAR2(30) NOT NULL,
    amount NUMBER(15,2) NOT NULL,
    tx_date VARCHAR2(30),
    tx_time VARCHAR2(30),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_ob_transactions_amount CHECK (amount > 0)
);

CREATE TABLE ob_kyc (
    kyc_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mobile VARCHAR2(20) NOT NULL,
    bank_code VARCHAR2(10) NOT NULL,
    status VARCHAR2(20) DEFAULT 'pending' NOT NULL,
    submitted_date VARCHAR2(30),
    submitted_time VARCHAR2(30),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_ob_kyc_status CHECK (status IN ('pending','approved','rejected')),
    CONSTRAINT fk_ob_kyc_bank FOREIGN KEY (bank_code) REFERENCES ob_banks(bank_code)
);

-- Browser compatibility snapshot. The normalized tables above are the DBMS-facing
-- tables; this CLOB keeps the supplied HTML application's state model persistent.
CREATE TABLE ob_state (
    state_id NUMBER PRIMARY KEY,
    state_json CLOB NOT NULL,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_ob_state_json CHECK (state_json IS JSON)
);

CREATE TABLE ob_employees (
    employee_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(30) NOT NULL UNIQUE,
    password_text VARCHAR2(255) NOT NULL,
    bank_code VARCHAR2(10) NOT NULL,
    CONSTRAINT fk_ob_employee_bank FOREIGN KEY (bank_code) REFERENCES ob_banks(bank_code)
);

CREATE TABLE ob_managers (
    manager_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(30) NOT NULL UNIQUE,
    password_text VARCHAR2(255) NOT NULL,
    bank_code VARCHAR2(10) NOT NULL,
    CONSTRAINT fk_ob_manager_bank FOREIGN KEY (bank_code) REFERENCES ob_banks(bank_code)
);

CREATE TABLE ob_ceo (
    ceo_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(30) NOT NULL UNIQUE,
    password_text VARCHAR2(255) NOT NULL
);

