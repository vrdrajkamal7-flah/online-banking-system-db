-- Trigger: balances can never become negative.
CREATE OR REPLACE TRIGGER trg_ob_accounts_balance
BEFORE INSERT OR UPDATE OF balance ON ob_accounts
FOR EACH ROW
BEGIN
    IF :NEW.balance < 0 THEN
        RAISE_APPLICATION_ERROR(-20001,'Insufficient balance: balance cannot be negative.');
    END IF;
END;
/

-- Trigger: every transaction must have two different accounts.
CREATE OR REPLACE TRIGGER trg_ob_transactions_accounts
BEFORE INSERT ON ob_transactions
FOR EACH ROW
BEGIN
    IF :NEW.sender_account = :NEW.receiver_account THEN
        RAISE_APPLICATION_ERROR(-20002,'Sender and receiver accounts must be different.');
    END IF;
END;
/

-- Stored procedure demonstrating an atomic Oracle transfer.
CREATE OR REPLACE PROCEDURE ob_transfer_money(
    p_sender_account   IN VARCHAR2,
    p_receiver_account IN VARCHAR2,
    p_amount           IN NUMBER
) AS
    v_sender_balance NUMBER;
BEGIN
    IF p_amount <= 0 THEN
        RAISE_APPLICATION_ERROR(-20003,'Transfer amount must be greater than zero.');
    END IF;

    SELECT balance INTO v_sender_balance
      FROM ob_accounts
     WHERE account_number = p_sender_account
       AND blocked = 0
     FOR UPDATE;

    IF v_sender_balance < p_amount THEN
        RAISE_APPLICATION_ERROR(-20004,'Insufficient balance.');
    END IF;

    UPDATE ob_accounts SET balance = balance - p_amount
     WHERE account_number = p_sender_account;

    UPDATE ob_accounts SET balance = balance + p_amount
     WHERE account_number = p_receiver_account
       AND blocked = 0;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20005,'Receiver account not found or blocked.');
    END IF;

    INSERT INTO ob_transactions(sender_account,receiver_account,amount,tx_date,tx_time)
    VALUES(p_sender_account,p_receiver_account,p_amount,
           TO_CHAR(SYSDATE,'DD-MM-YYYY'),TO_CHAR(SYSDATE,'HH:MI:SS AM'));

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

COMMIT;

